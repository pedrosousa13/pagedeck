// The emitted directive subset is closed, so `interpret.test-support.ts`' interpreter stays
// close to a transcription: CI cannot run nginx. `add_header` does not inherit into a block with
// its own.
import {
  covers,
  DEPLOY_DIRECTORY,
  DEPLOY_MANIFEST_PATH,
} from "@pagedeck/core/routing";
import type {
  HeaderField,
  RoutingTree,
  UpstreamRoute,
} from "@pagedeck/core/routing";

import { treeOf } from "@pagedeck/edge";
import type { CompiledTree, EdgeArtifact, Fault } from "@pagedeck/edge";

import {
  nginxLiteral,
  nginxLocation,
  unexpressibleInNginx,
  unexpressibleInNginxLocation,
} from "./encode.js";

function check(
  tree: RoutingTree,
  what: string,
  value: string,
  faults: Fault[],
  reason: (value: string) => string | undefined = unexpressibleInNginx,
): void {
  const why = reason(value);
  if (why !== undefined) {
    faults.push({
      kind: "unexpressible",
      line: `${treeOf(tree.domain)}'s ${what} — ${why}`,
    });
  }
}

// `always`: without it nginx adds the header only on 2xx and 3xx, and the 404 page is a 404.
function addHeader(field: HeaderField): string {
  return `    add_header ${nginxLiteral(field.name)} ${nginxLiteral(field.value)} always;`;
}

function addHeadersFor(tree: CompiledTree, path: string): string[] {
  const rule = tree.headers.find((candidate) =>
    path.startsWith(candidate.prefix),
  );
  return (rule?.set ?? []).map(addHeader);
}

export interface NginxOptions {
  /** The CA bundle each app's certificate is verified against; Debian's and Ubuntu's by default. */
  trustedCertificate?: string;
}

const DEFAULT_TRUSTED_CERTIFICATE = "/etc/ssl/certs/ca-certificates.crt";

const CONNECTION_VARIABLE = "$pagedeck_connection_upgrade";

// https://nginx.org/en/docs/http/websocket.html. `map` is valid only in the http context, which a
// server-block include cannot reach.
const HTTP_CONFIG = `# Generated by @pagedeck/edge from the routing document. Do not edit.
# Include once inside the http block, outside every server block; every tree's copy is the same.

map $http_upgrade ${CONNECTION_VARIABLE} {
    default upgrade;
    "" close;
}
`;

// No URI part on `proxy_pass`, so the request URI reaches the app as the client sent it. Any
// `proxy_set_header` here stops inheritance from the server and http levels, and leaves nginx's own
// `Host $proxy_host`, the name the app's certificate and virtual host answer to. Depth 2, not the
// default 1: a chain with two intermediates below a bundled root is the app host's choice.
function proxyBlock(
  location: string,
  url: string,
  trustedCertificate: string,
): string {
  return [
    `location ${location} {`,
    `    proxy_pass ${nginxLiteral(url)};`,
    `    proxy_http_version 1.1;`,
    `    proxy_set_header Upgrade $http_upgrade;`,
    `    proxy_set_header Connection ${CONNECTION_VARIABLE};`,
    `    proxy_set_header X-Forwarded-Host $host;`,
    `    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;`,
    `    proxy_set_header X-Forwarded-Proto $scheme;`,
    `    proxy_ssl_server_name on;`,
    `    proxy_ssl_verify on;`,
    `    proxy_ssl_verify_depth 2;`,
    `    proxy_ssl_trusted_certificate ${nginxLiteral(trustedCertificate)};`,
    `}`,
  ].join("\n");
}

function proxyBlocks(
  tree: CompiledTree,
  { prefix, url }: UpstreamRoute,
  trustedCertificate: string,
  faults: Fault[],
): string[] {
  check(
    tree,
    `upstream prefix "${prefix}"`,
    prefix,
    faults,
    unexpressibleInNginxLocation,
  );
  if (url === undefined) return [];
  check(tree, `upstream url for "${prefix}"`, url, faults);
  // Exact as well as `^~`: a proxied prefix location alone answers its unslashed path with a 301
  // (https://nginx.org/en/docs/http/ngx_http_core_module.html#location).
  return [
    proxyBlock(`= ${nginxLocation(prefix.slice(0, -1))}`, url, trustedCertificate),
    proxyBlock(`^~ ${nginxLocation(prefix)}`, url, trustedCertificate),
  ];
}

// The `internal` location keeps the 404 document from answering 200 at its own URL.
export function compileNginx(
  tree: CompiledTree,
  faults: Fault[],
  { trustedCertificate = DEFAULT_TRUSTED_CERTIFICATE }: NginxOptions = {},
): readonly EdgeArtifact[] {
  const sections: string[][] = [];
  const upstreams = tree.upstreams ?? [];

  // Refused, not dropped: compiling the rest would ship the primary with no word that the split
  // is gone.
  if (tree.experiments !== undefined) {
    const pages = tree.experiments.map((split) => `"${split.path}"`).join(", ");
    faults.push({
      kind: "unsupported",
      line: `${treeOf(tree.domain)}'s ${
        tree.experiments.length === 1 ? "experiment" : "experiments"
      } on ${pages} (build.routing.experiments)`,
    });
  }

  // At server level: rewrite directives run before location selection, where a `^~` header
  // rule under `/.pagedeck/` would win (#556). `$uri` is already decoded and dot-resolved.
  sections.push([
    `if ($uri = ${nginxLiteral(DEPLOY_MANIFEST_PATH)}) { return 404; }`,
    `if ($uri ~ "^${DEPLOY_DIRECTORY.replaceAll(".", "\\.")}(/|$)") { return 404; }`,
  ]);

  if (tree.redirects.length > 0) {
    sections.push(
      tree.redirects.map((rule) => {
        if (!rule.normalizing) {
          check(
            tree,
            `redirect from "${rule.from}"`,
            rule.from,
            faults,
            unexpressibleInNginxLocation,
          );
          // `to` keeps its escaped spelling: it is a URI in a `Location` header, not a location.
          check(tree, `redirect target on "${rule.from}"`, rule.to, faults);
        }
        const returned = `return ${String(rule.status)} ${nginxLiteral(rule.to)};`;
        const lines = addHeadersFor(tree, rule.from);
        return lines.length === 0
          ? `location = ${nginxLocation(rule.from)} { ${returned} }`
          : [
              `location = ${nginxLocation(rule.from)} {`,
              ...lines,
              `    ${returned}`,
              `}`,
            ].join("\n");
      }),
    );
  }

  // The app sets its own headers, and a header rule's prefix inside an upstream's governs only the
  // app's paths: emitted, its `^~` location would match as long or longer and take them from the proxy.
  const siteHeaders = tree.headers.filter(
    (rule) => !upstreams.some(({ prefix }) => covers(prefix, rule.prefix)),
  );
  for (const rule of siteHeaders) {
    check(
      tree,
      `header prefix "${rule.prefix}"`,
      rule.prefix,
      faults,
      unexpressibleInNginxLocation,
    );
    sections.push([
      `location ^~ ${nginxLocation(rule.prefix)} {`,
      ...rule.set.map((field) => {
        // Checked again: a compiler is handed a document, not necessarily one this `planRouting` wrote.
        check(
          tree,
          `header name "${field.name}" under prefix "${rule.prefix}"`,
          field.name,
          faults,
        );
        check(
          tree,
          `header "${field.name}" under prefix "${rule.prefix}"`,
          field.value,
          faults,
        );
        return addHeader(field);
      }),
      `}`,
    ]);
  }

  for (const upstream of upstreams) {
    const blocks = proxyBlocks(tree, upstream, trustedCertificate, faults);
    if (blocks.length > 0) sections.push(blocks);
  }

  if (tree.notFound !== undefined) {
    check(
      tree,
      "404 page",
      tree.notFound,
      faults,
      unexpressibleInNginxLocation,
    );
    // Both decoded: `error_page` sets the URI as written, and the location match does not decode it.
    const lines = addHeadersFor(tree, tree.notFound);
    sections.push([
      `error_page 404 ${nginxLocation(tree.notFound)};`,
      lines.length === 0
        ? `location = ${nginxLocation(tree.notFound)} { internal; }`
        : [
            `location = ${nginxLocation(tree.notFound)} {`,
            `    internal;`,
            ...lines,
            `}`,
          ].join("\n"),
    ]);
  }

  const contents = [
    `# Generated by @pagedeck/edge from the routing document. Do not edit.\n# Include inside the server block serving ${treeOf(tree.domain)}.`,
    ...sections.map((section) => section.join("\n")),
  ].join("\n\n");

  const domain = tree.domain === undefined ? {} : { domain: tree.domain };
  const routing: EdgeArtifact = {
    ...domain,
    role: "server-config",
    path: "routing.conf",
    contents: `${contents}\n`,
  };
  if (upstreams.length === 0) return [routing];
  return [
    routing,
    { ...domain, role: "server-config", path: "http.conf", contents: HTTP_CONFIG },
  ];
}
