import { describe, expect, it } from "vitest";

import { ConfigError } from "@pagedeck/core/exit";
import type { RoutingManifest } from "@pagedeck/core/routing";

import { FIXTURE } from "../../edge/src/fixture.test-support.js";
import { nginx } from "./index.js";

const WITH_UPSTREAMS: RoutingManifest = {
  ...FIXTURE,
  trees: FIXTURE.trees.map((tree) => ({
    ...tree,
    upstreams:
      tree.domain === undefined
        ? [
            { prefix: "/api/", url: "https://app.example" },
            { prefix: "/auth/", url: "https://auth.example:8443" },
          ]
        : [{ prefix: "/cart/", url: "https://cart.example" }],
  })),
};

function contentsOf(
  manifest: RoutingManifest,
  domain: string | undefined,
  path: string,
  adapter = nginx(),
): string {
  const artifact = adapter
    .compile(manifest)
    .artifacts.find(
      (candidate) => candidate.domain === domain && candidate.path === path,
    );
  if (artifact === undefined) throw new Error(`no ${path} for nginx`);
  return artifact.contents;
}

const HTTP_CONF = `# Generated by @pagedeck/edge from the routing document. Do not edit.
# Include once inside the http block, outside every server block; every tree's copy is the same.

map $http_upgrade $pagedeck_connection_upgrade {
    default upgrade;
    "" close;
}
`;

function proxied(location: string, url: string, bundle = "/etc/ssl/certs/ca-certificates.crt"): string {
  return `location ${location} {
    proxy_pass "${url}";
    proxy_http_version 1.1;
    proxy_set_header Upgrade $http_upgrade;
    proxy_set_header Connection $pagedeck_connection_upgrade;
    proxy_set_header X-Forwarded-Host $host;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_set_header X-Forwarded-Proto $scheme;
    proxy_ssl_server_name on;
    proxy_ssl_verify on;
    proxy_ssl_verify_depth 2;
    proxy_ssl_trusted_certificate "${bundle}";
}`;
}

describe("upstream prefixes", () => {
  it("refuses every tree that sends a prefix to an app with no url, in one report", () => {
    const manifest: RoutingManifest = {
      ...FIXTURE,
      trees: FIXTURE.trees.map((tree) => ({
        ...tree,
        upstreams:
          tree.domain === undefined
            ? [{ prefix: "/api/" }, { prefix: "/auth/", url: "https://auth.example" }]
            : [{ prefix: "/cart/" }],
      })),
    };
    expect(() => nginx().compile(manifest)).toThrow(
      new ConfigError(
        `Edge target "nginx": 2 trees send prefixes to apps with no url, which this target needs to reach each app — set url on each to the https origin the deployed app answers at, such as "https://app.example":
  the default tree's prefix "/api/" (build.routing.upstreams)
  the "shop.example" tree's prefix "/cart/" (build.routing.upstreams)`,
      ),
    );
  });

  it("proxies each prefix, unslashed path included, after the header rules", () => {
    expect(contentsOf(WITH_UPSTREAMS, undefined, "routing.conf")).toContain(
      `location ^~ "/en/" {
    add_header "X-Content-Type-Options" "nosniff" always;
    add_header "Referrer-Policy" "strict-origin-when-cross-origin" always;
}

${proxied('= "/api"', "https://app.example")}
${proxied('^~ "/api/"', "https://app.example")}

${proxied('= "/auth"', "https://auth.example:8443")}
${proxied('^~ "/auth/"', "https://auth.example:8443")}

error_page 404 "/en/404";`,
    );
  });

  it("writes a domain tree's proxy into that tree's fragment, beside its own map file", () => {
    expect(contentsOf(WITH_UPSTREAMS, "shop.example", "routing.conf"))
      .toBe(`# Generated by @pagedeck/edge from the routing document. Do not edit.
# Include inside the server block serving the "shop.example" tree.

if ($uri = "/manifest.json") { return 404; }
if ($uri ~ "^/\\.pagedeck(/|$)") { return 404; }

location = "/deals/" {
    add_header "X-Content-Type-Options" "nosniff" always;
    return 308 "/deals";
}
location = "/sale" {
    add_header "X-Content-Type-Options" "nosniff" always;
    return 302 "/deals";
}
location = "/sale/" {
    add_header "X-Content-Type-Options" "nosniff" always;
    return 302 "/deals";
}

location ^~ "/" {
    add_header "X-Content-Type-Options" "nosniff" always;
}

${proxied('= "/cart"', "https://cart.example")}
${proxied('^~ "/cart/"', "https://cart.example")}

error_page 404 "/shop-404";
location = "/shop-404" {
    internal;
    add_header "X-Content-Type-Options" "nosniff" always;
}
`);
    expect(contentsOf(WITH_UPSTREAMS, "shop.example", "http.conf")).toBe(HTTP_CONF);
    expect(contentsOf(WITH_UPSTREAMS, undefined, "http.conf")).toBe(HTTP_CONF);
  });

  it("quotes a prefix nginx would otherwise split, decoded as nginx matches it", () => {
    const manifest: RoutingManifest = {
      ...FIXTURE,
      trees: [
        {
          redirects: [],
          headers: [],
          upstreams: [{ prefix: "/my%20app;v1/", url: "https://app.example" }],
        },
      ],
    };
    expect(contentsOf(manifest, undefined, "routing.conf")).toBe(
      `# Generated by @pagedeck/edge from the routing document. Do not edit.
# Include inside the server block serving the default tree.

if ($uri = "/manifest.json") { return 404; }
if ($uri ~ "^/\\.pagedeck(/|$)") { return 404; }

${proxied('= "/my app;v1"', "https://app.example")}
${proxied('^~ "/my app;v1/"', "https://app.example")}
`,
    );
  });

  it("verifies the app's certificate against the bundle the site names", () => {
    expect(
      contentsOf(
        WITH_UPSTREAMS,
        "shop.example",
        "routing.conf",
        nginx({ trustedCertificate: "/etc/pki/tls/certs/ca-bundle.crt" }),
      ),
    ).toContain(
      proxied('^~ "/cart/"', "https://cart.example", "/etc/pki/tls/certs/ca-bundle.crt"),
    );
  });

  it("emits no location for a header rule inside a prefix, which the app's response would otherwise carry", () => {
    const manifest: RoutingManifest = {
      ...FIXTURE,
      trees: [
        {
          redirects: [],
          headers: [
            { prefix: "/api/v1/", set: [{ name: "X-Frame-Options", value: "DENY" }] },
            { prefix: "/", set: [{ name: "X-Content-Type-Options", value: "nosniff" }] },
          ],
          upstreams: [{ prefix: "/api/", url: "https://app.example" }],
        },
      ],
    };
    const contents = contentsOf(manifest, undefined, "routing.conf");
    expect(contents).not.toContain("/api/v1/");
    expect(contents).toContain(`location ^~ "/" {`);
  });

  it("refuses a url holding a character nginx would read as a variable", () => {
    const manifest: RoutingManifest = {
      ...FIXTURE,
      trees: [
        {
          redirects: [],
          headers: [],
          upstreams: [{ prefix: "/api/", url: "https://a$b.example" }],
        },
      ],
    };
    expect(() => nginx().compile(manifest)).toThrow(
      new ConfigError(
        `Edge target "nginx": 1 value cannot be expressed by this target — change each value as its line says, or compile a target that can express it:
  the default tree's upstream url for "/api/" — nginx interpolates "$" inside a quoted string, and offers no escape for a literal one`,
      ),
    );
  });

  it("writes no map file for a tree with no upstream", () => {
    expect(
      nginx()
        .compile(FIXTURE)
        .artifacts.map(({ domain, path }) => [domain, path]),
    ).toEqual([
      [undefined, "routing.conf"],
      ["shop.example", "routing.conf"],
    ]);
  });
});
